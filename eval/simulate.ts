import { writeFileSync } from 'node:fs';
import { estimate, probability, type ItemResponse } from '../backend/src/common/irt.ts';
import { seededRandom, selectFamily, type Family } from '../backend/src/common/cat.ts';

const random = seededRandom(20261009);
const bank: Family[] = Array.from({ length: 100 }, (_, i) => ({ id: `synthetic-${i}`, a: 1.2, b: -2.5 + i / 99 * 5, competency: ['language', 'sql', 'architecture'][i % 3]! }));
const policy = { min: 10, max: 18, targetSe: 0.35, topK: 5, maxExposure: 0.2 };
function normal(): number { return Math.sqrt(-2 * Math.log(Math.max(1e-12, random()))) * Math.cos(2 * Math.PI * random()); }
function run(theta: number) {
  const responses: ItemResponse[] = [], servedIds: string[] = [], competencyCounts: Record<string, number> = {};
  while (true) {
    const { family } = selectFamily(bank, { responses, servedIds, competencyCounts }, policy, {}, ['language', 'sql', 'architecture'], random);
    if (!family) break;
    responses.push({ a: family.a, b: family.b, correct: random() < probability(theta, family) });
    servedIds.push(family.id);
    competencyCounts[family.competency] = (competencyCounts[family.competency] ?? 0) + 1;
  }
  const result = estimate(responses);
  return { theta: result.theta, se: result.se, length: responses.length };
}
function mean(xs: number[]): number { return xs.reduce((s, x) => s + x, 0) / xs.length; }
function correlation(a: number[], b: number[]): number {
  const ma = mean(a), mb = mean(b);
  return a.reduce((s, x, i) => s + (x - ma) * (b[i]! - mb), 0) / Math.sqrt(a.reduce((s, x) => s + (x - ma) ** 2, 0) * b.reduce((s, x) => s + (x - mb) ** 2, 0));
}
function grade(theta: number): string { return theta < -1.3 ? 'unconfirmed' : theta < -0.2 ? 'junior' : theta < 0.8 ? 'middle' : theta < 1.6 ? 'senior' : 'lead'; }
const n = Number(process.argv[2] ?? 200);
if (!Number.isInteger(n) || n < 10 || n > 10000) throw new Error('N must be an integer between 10 and 10000');
const candidates = Array.from({ length: n }, () => {
  const truth = normal();
  return { truth, first: run(truth), second: run(truth) };
});
const report = {
  dataset: 'synthetic_model_consistency_only', seed: 20261009, n,
  limitations: [
    'Responses are generated by the same assumed 2PL model used by the estimator; these are not real-world validation results.',
    'Synthetic families do not represent the actual task bank or empirical calibration.',
    'Grade classification uses theta bands for a diagnostic; production decisions additionally use posterior confidence.',
    'Exposure control is not evaluated in this experiment.',
  ],
  measurements: {
    theta_rmse: Math.sqrt(mean(candidates.map(c => (c.first.theta - c.truth) ** 2))),
    test_retest_correlation: correlation(candidates.map(c => c.first.theta), candidates.map(c => c.second.theta)),
    grade_agreement: mean(candidates.map(c => Number(grade(c.first.theta) === grade(c.second.theta)))),
    grade_accuracy_synthetic: mean(candidates.map(c => Number(grade(c.first.theta) === grade(c.truth)))),
    average_items: mean(candidates.map(c => c.first.length)),
    average_se: mean(candidates.map(c => c.first.se)),
  },
};
writeFileSync(new URL('./synthetic-report.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
